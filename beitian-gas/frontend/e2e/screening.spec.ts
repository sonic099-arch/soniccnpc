import {test,expect} from '@playwright/test'
const errors:string[]=[]
test.beforeEach(async({page})=>{errors.length=0;page.on('pageerror',e=>errors.push(e.message))})
test.afterEach(()=>expect(errors).toEqual([]))
test('首页1001井统计及按状态下钻',async({page})=>{
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'气井生产概览'})).toBeVisible()
 const total=page.locator('.total-card');await expect(total).toContainText('1,001')
 const abnormal=page.locator('.stat-card').filter({hasText:'疑似异常'});await expect(abnormal).toContainText('385')
 await expect(page.locator('.overview-charts [role="img"] svg').first()).toBeVisible()
 await page.screenshot({path:'../work/task4-dashboard.png',fullPage:true})
 await abnormal.click();await expect(page).toHaveURL(/screening_status=/)
 await expect(page.locator('.count-label')).toContainText('385')
 await expect(page.locator('tbody .el-tag').filter({hasText:'疑似异常'}).first()).toBeVisible()
})
test('井号搜索、清空和正常井单井曲线',async({page})=>{
 await page.goto('/wells')
 await page.getByPlaceholder('搜索井号').fill('演示-BT-0001')
 await page.getByRole('button',{name:'查询',exact:true}).click()
 await expect(page.locator('.count-label')).toContainText('共 1 口')
 await page.locator('a.well-link').click()
 await expect(page.getByRole('heading',{name:'演示-BT-0001'})).toBeVisible()
 await expect(page.locator('.curve-grid [role="img"]')).toHaveCount(7)
 await expect(page.locator('.curve-grid svg')).toHaveCount(7)
 await expect(page.getByText('演示数据：曲线、参数和规则阈值不构成现场工艺标准；疑似积液、冻堵仅提供辅助提示。')).toBeVisible()
 await page.getByText('末7天',{exact:true}).click()
 await expect(page.getByText('当前窗口 168 个采样',{exact:false})).toBeVisible()
 await page.goto('/wells?search=演示-BT-0001')
 await page.getByRole('button',{name:'清空筛选'}).click()
 await expect(page.locator('.count-label')).toContainText('共 1001 口')
})
